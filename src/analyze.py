"""
Loads the cleaned applications into SQLite, runs the SQL analysis queries,
saves charts to reports/figures and writes reports/findings.md.
"""
import sqlite3
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "enrolment.db"
FIG = ROOT / "reports" / "figures"
BLUE, ORANGE, GREY = "#1F4E79", "#E07B39", "#9AA5B1"


def load_queries():
    text = (ROOT / "sql" / "analysis_queries.sql").read_text(encoding="utf-8")
    queries, name = {}, None
    for line in text.splitlines():
        if line.startswith("-- name:"):
            name = line.split(":", 1)[1].strip()
            queries[name] = ""
        elif name:
            queries[name] += line + "\n"
    return queries


def build_db():
    DB.unlink(missing_ok=True)
    con = sqlite3.connect(DB)
    con.executescript((ROOT / "sql" / "schema.sql").read_text(encoding="utf-8"))
    for table in ("programs", "terms"):
        pd.read_csv(ROOT / "data" / f"{table}.csv").to_sql(table, con, if_exists="append", index=False)
    apps = pd.read_csv(ROOT / "data" / "clean_applications.csv")
    for col in ("first_term_gpa", "retained_next_term"):
        apps[col] = apps[col].astype(object).where(apps[col].notna(), None)
    apps.to_sql("applications", con, if_exists="append", index=False)
    return con


def style(ax, title, xlabel="", ylabel=""):
    ax.set_title(title, loc="left", fontsize=13, fontweight="bold")
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.spines[["top", "right"]].set_visible(False)


def save(fig, name):
    fig.tight_layout()
    fig.savefig(FIG / name, dpi=150)
    plt.close(fig)


def charts(r):
    FIG.mkdir(parents=True, exist_ok=True)

    f = r["funnel"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    bars = ax.barh(f["stage"][::-1], f["students"][::-1], color=[BLUE, BLUE, GREY, GREY, GREY][::-1])
    for b, v in zip(bars, f["students"][::-1]):
        ax.text(b.get_width(), b.get_y() + b.get_height() / 2,
                f"  {v:,} ({100 * v / f['students'][0]:.0f}%)", va="center")
    ax.set_xlim(0, f["students"].max() * 1.22)
    style(ax, "Admissions funnel: where applicants drop out", "Students")
    save(fig, "01_enrolment_funnel.png")

    t = r["by_term"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.bar(t["term"], t["domestic_apps"], color=BLUE, label="Domestic")
    ax.bar(t["term"], t["international_apps"], bottom=t["domestic_apps"], color=ORANGE, label="International")
    ax.legend(frameon=False)
    style(ax, "Applications by term: international demand falls from 2024F", "Term", "Applications")
    save(fig, "02_applications_by_term.png")

    p = r["by_program"].sort_values("offer_rate_pct")
    fig, ax = plt.subplots(figsize=(8, 4.6))
    colors = [ORANGE if v < 50 else BLUE for v in p["offer_rate_pct"]]
    bars = ax.barh(p["program_name"], p["offer_rate_pct"], color=colors)
    for b, v in zip(bars, p["offer_rate_pct"]):
        ax.text(b.get_width(), b.get_y() + b.get_height() / 2, f" {v:.0f}%", va="center")
    ax.set_xlim(0, 105)
    style(ax, "Offer rate by program: Nursing is capacity-limited", "% of applicants offered a seat")
    save(fig, "03_offer_rate_by_program.png")

    g = r["retention_by_gpa"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    labels = g["gpa_band"].str.split(": ").str[1]
    colors = [ORANGE if v < 70 else BLUE for v in g["retention_pct"]]
    bars = ax.bar(labels, g["retention_pct"], color=colors)
    for b, v in zip(bars, g["retention_pct"]):
        ax.text(b.get_x() + b.get_width() / 2, b.get_height() + 1, f"{v:.0f}%", ha="center")
    ax.set_ylim(0, 105)
    style(ax, "Retention into next term by first-term GPA", "First-term GPA", "% retained")
    save(fig, "04_retention_by_gpa.png")


def findings(r):
    k = r["kpis"].iloc[0]
    prog = r["by_program"].set_index("program_name")
    yt = r["yield_by_type"].set_index("student_type")
    t = r["by_term"]
    g = r["retention_by_gpa"].set_index("gpa_band")
    intake = r["retention_by_intake"].set_index("intake")
    ch = r["by_channel"]
    intl_ch = ch[ch["student_type"] == "International"].set_index("channel")
    first, last = t.iloc[0], t[t["term"].str.endswith("F")].iloc[-1]
    intl_drop = 100 * (1 - last["international_apps"] / first["international_apps"])
    rev_first, rev_last = first["tuition_revenue"], last["tuition_revenue"]
    low_gpa = g.loc["1: Below 2.0", "retention_pct"]
    high_gpa = g.loc["5: 3.5+", "retention_pct"]
    worst_ret = prog["retention_pct"].idxmin()

    text = f"""# Findings: Student Enrolment Analysis

*All figures come from synthetic data generated by `src/generate_data.py`.*

## Headline numbers

| Metric | Value |
|---|---|
| Applications analyzed | {int(k.applications):,} |
| Offer rate | {k.offer_rate_pct}% |
| Yield (offers that became enrolments) | {k.yield_pct}% |
| Students enrolled | {int(k.enrolled):,} |
| Retained into next term | {k.retention_pct}% |

## 1. International applications fell sharply
Fall international applications dropped **{intl_drop:.0f}%** from {first.term} to {last.term}
({first.international_apps:,} to {last.international_apps:,}), while domestic applications grew slightly.
First-term tuition from new Fall students moved from **${rev_first:,.0f}** to **${rev_last:,.0f}**.
This pattern is consistent with the study-permit caps introduced in 2024.

## 2. International offers convert far less often
Domestic yield is **{yt.loc['Domestic', 'yield_pct']}%**, international **{yt.loc['International', 'yield_pct']}%**.
The biggest gap is after acceptance: only **{yt.loc['International', 'show_up_pct']}%** of international
students who accept actually enrol (domestic: {yt.loc['Domestic', 'show_up_pct']}%), which points to visa
and arrival problems rather than lack of interest. Among international channels, Referral converts at
**{intl_ch.loc['Referral', 'conversion_pct']}%** of applications versus **{intl_ch.loc['Agent', 'conversion_pct']}%** for Agent.

## 3. Practical Nursing is capacity-limited
Nursing offers a seat to only **{prog.loc['Practical Nursing', 'offer_rate_pct']}%** of applicants,
compared with {prog['offer_rate_pct'].drop('Practical Nursing').min()}-{prog['offer_rate_pct'].max()}% elsewhere.
Demand is there; seats are the constraint.

## 4. First-term GPA predicts retention
Students with a first-term GPA below 2.0 are retained **{low_gpa}%** of the time, versus **{high_gpa}%**
for 3.5+. Winter-intake students are retained **{intake.loc['Winter', 'retention_pct']}%** vs
**{intake.loc['Fall', 'retention_pct']}%** for Fall. {worst_ret} has the lowest retention
(**{prog.loc[worst_ret, 'retention_pct']}%**, average GPA {prog.loc[worst_ret, 'avg_gpa']}).

## Recommendations
1. **Rebalance recruitment toward domestic and diversified markets** to offset the international decline;
   set intake targets per program using the term trend, not the 2023 baseline.
2. **Add a pre-arrival support track for international admits** (visa checklist, deposit reminders,
   arrival dates) to lift the {yt.loc['International', 'show_up_pct']}% show-up rate.
3. **Grow referral and alumni programs** and review agent contracts on conversion, not volume.
4. **Make the case for more Nursing seats** (or a waitlist-to-bridging pathway) given unmet demand.
5. **Flag students below 2.0 GPA after first-term grades** for advising and tutoring, with
   extra onboarding for Winter intake and {worst_ret}.
"""
    (ROOT / "reports" / "findings.md").write_text(text, encoding="utf-8")


def main():
    con = build_db()
    r = {name: pd.read_sql_query(sql, con) for name, sql in load_queries().items()}
    con.close()
    charts(r)
    findings(r)
    pd.set_option("display.width", 140)
    for name in ("kpis", "yield_by_type", "by_program", "retention_by_gpa", "retention_by_intake", "by_term", "by_channel"):
        print(f"\n-- {name}\n{r[name].to_string(index=False)}")
    print("\nCharts saved to reports/figures, findings written to reports/findings.md")


if __name__ == "__main__":
    main()
